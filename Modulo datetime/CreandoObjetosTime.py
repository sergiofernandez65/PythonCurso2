from datetime import time

t = time(14, 53, 20, 1)

print("Tiempo:", t)
print("Hora:", t.hour)
print("Minutos:", t.minute)
print("Segundos:", t.second)
print("Microsegundo:", t.microsecond)
    
#Resultado:
#Tiempo: 14:53:20.000001
#Hora: 14
#Minutos: 53
#Segundos: 20
#Microsegundo: 1
